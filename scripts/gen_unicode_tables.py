#!/usr/bin/env python3
"""Generate src/core/unicode_tables.rs from the running CPython.

Every table is read off CPython's own string methods, so the compiler's
case mappings and character classes are CPython's by construction. Run it
with the CPython the project is checked against (3.13, Unicode 15.1.0):

    python3 scripts/gen_unicode_tables.py > src/core/unicode_tables.rs
"""
import sys
import unicodedata

CHARS = [chr(cp) for cp in range(0x110000)]


def ranges(pred):
    out = []
    for cp, c in enumerate(CHARS):
        if pred(c):
            if out and out[-1][1] == cp - 1:
                out[-1][1] = cp
            else:
                out.append([cp, cp])
    return out


def final(s):
    return s[-1] == "ς"


def cased(c):
    # title() lowers the character after a cased one and titles the one after
    # anything else.
    return ("x" + c + "a").title()[-1] == "a"


def case_ignorable(c):
    # The final-sigma rule skips case-ignorable characters when it looks for
    # a cased one before the sigma.
    if cased(c):
        return not final((c + "Σ").lower())
    return final(("A" + c + "Σ").lower())


def mapping(f):
    """Single-character mappings as runs (start, end, step, delta), and the
    mappings to several characters on their own. The lowercase of a capital
    sigma is the plain sigma here; the final form is a rule, not a mapping."""
    runs, multi = [], []
    for cp, c in enumerate(CHARS):
        m = f(c)
        if m == c:
            continue
        if len(m) != 1:
            multi.append((cp, [ord(x) for x in m]))
            continue
        d = ord(m) - cp
        if runs:
            start, end, step, delta = runs[-1]
            if delta == d and start == end and cp - start in (1, 2):
                runs[-1] = [start, cp, cp - start, d]
                continue
            if delta == d and cp - end == step:
                runs[-1][1] = cp
                continue
        runs.append([cp, cp, 1, d])
    return runs, multi


def title_char(c):
    # The titlecase of one character: what title() gives it at a word start.
    t = c.title()
    return t


def emit_ranges(name, rs):
    print(f"pub const {name}: &[(u32, u32)] = &[")
    line = "   "
    for a, b in rs:
        item = f" (0x{a:x}, 0x{b:x}),"
        if len(line) + len(item) > 99:
            print(line)
            line = "   "
        line += item
    print(line)
    print("];")
    print()


def emit_map(name, f):
    runs, multi = mapping(f)
    print(f"pub const {name}_RUNS: &[(u32, u32, u32, i32)] = &[")
    for start, end, step, delta in runs:
        print(f"    (0x{start:x}, 0x{end:x}, {step}, {delta}),")
    print("];")
    print()
    print(f"pub const {name}_MULTI: &[(u32, [u32; 3], u32)] = &[")
    for cp, ms in multi:
        padded = ms + [0] * (3 - len(ms))
        print(f"    (0x{cp:x}, [0x{padded[0]:x}, 0x{padded[1]:x}, 0x{padded[2]:x}], {len(ms)}),")
    print("];")
    print()


def main():
    print("// Generated by scripts/gen_unicode_tables.py from CPython "
          f"{sys.version.split()[0]} (Unicode {unicodedata.unidata_version}). Do not edit.")
    print("//")
    print("// Inclusive code point ranges, sorted; and case mappings as runs of")
    print("// (start, end, step, delta) plus the mappings to several characters.")
    print()
    print(f'pub const UNICODE_VERSION: &str = "{unicodedata.unidata_version}";')
    print()
    emit_ranges("ALPHA", ranges(str.isalpha))
    emit_ranges("DECIMAL", ranges(str.isdecimal))
    emit_ranges("DIGIT", ranges(str.isdigit))
    emit_ranges("NUMERIC", ranges(str.isnumeric))
    emit_ranges("SPACE", ranges(str.isspace))
    emit_ranges("UPPER", ranges(str.isupper))
    emit_ranges("LOWER", ranges(str.islower))
    emit_ranges("TITLE", ranges(lambda c: unicodedata.category(c) == "Lt"))
    emit_ranges("CASED", ranges(cased))
    emit_ranges("CASE_IGNORABLE", ranges(case_ignorable))
    emit_map("TO_UPPER", str.upper)
    emit_map("TO_LOWER", str.lower)
    emit_map("TO_TITLE", title_char)


main()
